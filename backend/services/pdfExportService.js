const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

class PDFExportService {
    static async generateHealthReport(child, healthRecords = [], prediction = null, vaccinationStatus = null) {
        return new Promise((resolve, reject) => {
            try {
                const doc = new PDFDocument({ margin: 50 });
                const chunks = [];
                
                doc.on('data', chunk => chunks.push(chunk));
                doc.on('end', () => resolve(Buffer.concat(chunks)));
                doc.on('error', reject);

                // Header
                doc.fontSize(20).text('HEALTH REPORT', { align: 'center' });
                doc.moveTo(50, 80).lineTo(550, 80).stroke();
                doc.moveDown(2);

                // Child Info
                doc.fontSize(14).text('CHILD INFORMATION', { underline: true }).moveDown(0.5);
                doc.fontSize(12)
                   .text(`Name: ${child.firstName} ${child.lastName || ''}`)
                   .text(`DOB: ${new Date(child.dateOfBirth).toLocaleDateString()}`)
                   .text(`Gender: ${child.gender || 'Not specified'}`)
                   .moveDown();

                // Health Records
                doc.addPage().fontSize(14).text('HEALTH RECORDS', { underline: true }).moveDown(0.5);
                if (healthRecords?.length > 0) {
                    healthRecords.forEach((record, i) => {
                        doc.fontSize(12)
                           .text(`Record #${i+1} - ${record.type || 'General'} (${new Date(record.createdAt).toLocaleDateString()})`)
                           .moveDown(0.2);
                        if (record.notes) doc.fontSize(11).text(record.notes, { indent: 20 }).moveDown(0.5);
                        const details = [];
                        if (record.height) details.push(`Height: ${record.height}cm`);
                        if (record.weight) details.push(`Weight: ${record.weight}kg`);
                        if (details.length) doc.fontSize(10).text(details.join(' | '), { indent: 20 });
                        doc.moveDown(0.8);
                    });
                }

                // Prediction
                if (prediction) {
                    doc.addPage().fontSize(14).text('GROWTH PREDICTION', { underline: true }).moveDown(0.5);
                    if (prediction.nextMonthPrediction) {
                        const p = prediction.nextMonthPrediction;
                        doc.fontSize(12)
                           .text(`Next Month: Height: ${p.predictedHeight}cm, Weight: ${p.predictedWeight}kg`)
                           .moveDown(0.5);
                    }
                }

                // Vaccination Status
                if (vaccinationStatus) {
                    doc.addPage().fontSize(14).text('VACCINATION STATUS', { underline: true }).moveDown(0.5);
                    const statuses = {
                        'completedVaccines': '✅ Completed',
                        'dueVaccines': '⏳ Due',
                        'overdueVaccines': '⚠️ Overdue'
                    };
                    Object.entries(statuses).forEach(([key, label]) => {
                        if (vaccinationStatus[key]?.length) {
                            doc.fontSize(12).font('Helvetica-Bold').text(`${label}:`).font('Helvetica');
                            vaccinationStatus[key].forEach(v => {
                                doc.text(`• ${v.name}`, { indent: 20 });
                            });
                        }
                    });
                }

                // Footer
                const footerY = doc.page.height - 50;
                doc.fontSize(10)
                   .text('Generated by Pediatric Health Tracker', 50, footerY, { align: 'center', width: doc.page.width - 100 })
                   .text(`Generated on: ${new Date().toLocaleString()}`, 50, footerY + 20, { align: 'center', width: doc.page.width - 100 });

                doc.end();
            } catch (error) {
                console.error('Error generating PDF:', error);
                reject(error);
            }
        });
    }
}

module.exports = PDFExportService;